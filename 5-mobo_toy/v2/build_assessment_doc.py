def rng(v, n=0, unit=""):
    v = [x for x in v if x is not None]
    if not v:
        return "—"
    a, b = min(v), max(v)
    return f"{a:.{n}f}{unit}" if abs(a - b) < 0.5 * 10 ** (-n) else f"{a:.{n}f}–{b:.{n}f}{unit}"


