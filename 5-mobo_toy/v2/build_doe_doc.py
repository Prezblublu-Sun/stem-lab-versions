def rho_lower(rho, n):
    return math.tanh(math.atanh(rho) - 1.96 * 1.03 / math.sqrt(n - 3))


def n_seeds(sd, delta):
    return max(3, math.ceil(2 * (1.96 + 0.8416) ** 2 * sd ** 2 / delta ** 2))       # 少于 3 个种子估不出波动，最少取 3


def m1_sweep(label):
    out = {}
    for r in M1["rows"]:
        if (r.get("label") == label and r.get("f1_p95_um") is not None and abs(r.get("h", 0) - 2.0) < 1e-9 and abs((r.get("slip_tol") or 0) - 2.5e-4) < 1e-9
                and not r.get("lagrange") and abs(r.get("mu", 0.3) - 0.3) < 1e-9 and r.get("torque", True)):
            out[round(r["delta"], 4)] = r
    return out


def loginterp(x0, y0, x1, y1, x):
    f = (math.log(x) - math.log(x0)) / (math.log(x1) - math.log(x0))
    return math.exp(math.log(y0) + f * (math.log(y1) - math.log(y0)))


